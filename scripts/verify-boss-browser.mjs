import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1200,height:800}}),page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
await page.goto('http://127.0.0.1:8086');await page.locator('#loadingBar').waitFor({state:'hidden'});
await page.locator('#playerNameInput').fill('Boss验收A');await page.locator('#roomTitleInput').fill('迷雾Boss本地验收');
await page.locator('#btnHost').click();await page.locator('#btnEnterRoom').waitFor({state:'visible'});await page.locator('#btnEnterRoom').click();
await page.locator('#bossHud').waitFor({state:'visible'});
await page.bringToFront();
await page.waitForTimeout(200);
if(await page.locator('#pauseScreen').isVisible()) await page.locator('#btnResume').click();
console.log('pause after resume',await page.locator('#pauseScreen').isVisible());
await mkdir('docs/verification',{recursive:true});
await page.waitForTimeout(1700);await page.screenshot({path:'docs/verification/online-boss.png'});
assert.equal(await page.locator('#bossHpText').textContent(),'1500 / 1500');
await page.keyboard.press('q');await page.mouse.move(600,400);await page.mouse.down();await page.waitForTimeout(350);await page.mouse.up();
await page.waitForFunction(()=>parseInt(document.getElementById('bossHpText').textContent)<1500);
console.log('HUD',await page.locator('#bossHpText').textContent(),'hp',await page.locator('#hpHearts').textContent());
await page.locator('#deathScreen').waitFor({state:'visible',timeout:18000});
console.log('death',await page.locator('#deathReason').textContent());await page.screenshot({path:'docs/verification/online-death.png'});
await page.locator('#btnRespawn').click();await page.locator('#deathScreen').waitFor({state:'hidden'});
console.log('respawn HP',await page.locator('#hpHearts').textContent(),'pause',await page.locator('#pauseScreen').isVisible());
if(await page.locator('#pauseScreen').isVisible()) await page.locator('#btnResume').click();
assert.equal(await page.locator('#hpHearts').textContent(),'20 / 20');
await page.screenshot({path:'docs/verification/online-respawn.png'});
console.log('ERRORS',errors);await browser.close();assert.deepEqual(errors,[]);
